//! Rust code generation from parsed registry data.

use super::parse::{ModelsFile, PlatformFile, PlatformVariant};
use std::{fmt::Write, path::Path};

/// Generate `quantization.rs` containing `QuantizationType` and `MemoryThreshold`.
pub fn write_quantization(platform: &PlatformFile, out_dir: &Path) {
    let mut code = String::new();

    // ── QuantizationType enum ──────────────────────────────────────
    writeln!(code, "/// Platform-specific quantization types.").unwrap();
    writeln!(code, "///").unwrap();
    writeln!(code, "/// Generated by build.rs from registry TOML files.").unwrap();
    writeln!(
        code,
        "#[derive(Debug, Clone, Copy, serde::Serialize, serde::Deserialize)]"
    )
    .unwrap();
    writeln!(code, "pub enum QuantizationType {{").unwrap();

    for serde_name in platform.quantizations.keys() {
        let variant = to_enum_variant(serde_name);
        writeln!(code, "    #[serde(rename = \"{serde_name}\")]").unwrap();
        writeln!(code, "    {variant},").unwrap();
    }

    writeln!(code, "}}").unwrap();
    writeln!(code).unwrap();

    // ── to_isq() impl ─────────────────────────────────────────────
    writeln!(code, "#[cfg(feature = \"local\")]").unwrap();
    writeln!(code, "impl QuantizationType {{").unwrap();
    writeln!(code, "    /// Convert to the mistralrs `IsqType`.").unwrap();
    writeln!(code, "    pub fn to_isq(self) -> mistralrs::IsqType {{").unwrap();
    writeln!(code, "        match self {{").unwrap();

    for (serde_name, isq_variant) in &platform.quantizations {
        let variant = to_enum_variant(serde_name);
        writeln!(
            code,
            "            Self::{variant} => mistralrs::IsqType::{isq_variant},"
        )
        .unwrap();
    }

    writeln!(code, "        }}").unwrap();
    writeln!(code, "    }}").unwrap();
    writeln!(code, "}}").unwrap();
    writeln!(code).unwrap();

    // ── MemoryThreshold enum ───────────────────────────────────────
    writeln!(code, "/// Minimum system RAM required for a model.").unwrap();
    writeln!(code, "///").unwrap();
    writeln!(code, "/// Generated by build.rs from registry TOML files.").unwrap();
    writeln!(
        code,
        "#[derive(Debug, Clone, Copy, serde::Serialize, serde::Deserialize)]"
    )
    .unwrap();
    writeln!(code, "pub enum MemoryThreshold {{").unwrap();

    for (name, variant, gb) in MEMORY_THRESHOLDS {
        writeln!(code, "    #[serde(rename = \"{name}\")]").unwrap();
        writeln!(code, "    /// {gb} GB minimum.").unwrap();
        writeln!(code, "    {variant},").unwrap();
    }

    writeln!(code, "}}").unwrap();
    writeln!(code).unwrap();
    writeln!(code, "impl MemoryThreshold {{").unwrap();
    writeln!(code, "    /// Return the threshold in bytes.").unwrap();
    writeln!(code, "    pub fn bytes(self) -> u64 {{").unwrap();
    writeln!(code, "        match self {{").unwrap();

    for (_, variant, gb) in MEMORY_THRESHOLDS {
        let bytes: u64 = *gb * 1024 * 1024 * 1024;
        writeln!(code, "            Self::{variant} => {bytes},").unwrap();
    }

    writeln!(code, "        }}").unwrap();
    writeln!(code, "    }}").unwrap();
    writeln!(code, "}}").unwrap();

    let out_path = out_dir.join("quantization.rs");
    std::fs::write(&out_path, code)
        .unwrap_or_else(|e| panic!("failed to write {}: {e}", out_path.display()));
}

/// Generate `registry.rs` containing `ModelEntry`, `MODELS`, `PlatformDefaults`, `DEFAULTS`.
pub fn write_registry(
    platform: &PlatformFile,
    models: &ModelsFile,
    platform_name: &str,
    out_dir: &Path,
) {
    let mut code = String::new();

    // ── ModelEntry struct ──────────────────────────────────────────
    writeln!(code, "/// A curated model entry from the registry.").unwrap();
    writeln!(code, "///").unwrap();
    writeln!(code, "/// Generated by build.rs from registry TOML files.").unwrap();
    writeln!(code, "#[derive(Debug, Clone, Copy)]").unwrap();
    writeln!(code, "pub struct ModelEntry {{").unwrap();
    writeln!(code, "    /// Registry key (e.g. \"qwen3-4b\").").unwrap();
    writeln!(code, "    pub key: &'static str,").unwrap();
    writeln!(code, "    /// Human-readable name.").unwrap();
    writeln!(code, "    pub name: &'static str,").unwrap();
    writeln!(code, "    /// HuggingFace model ID.").unwrap();
    writeln!(code, "    pub model_id: &'static str,").unwrap();
    writeln!(code, "    /// Loader to use.").unwrap();
    writeln!(code, "    pub loader: crate::config::Loader,").unwrap();
    writeln!(code, "    /// Recommended quantization.").unwrap();
    writeln!(
        code,
        "    pub quantization: Option<crate::config::QuantizationType>,"
    )
    .unwrap();
    writeln!(code, "    /// Minimum system RAM.").unwrap();
    writeln!(
        code,
        "    pub memory: Option<crate::config::MemoryThreshold>,"
    )
    .unwrap();
    writeln!(code, "}}").unwrap();
    writeln!(code).unwrap();

    // ── MODELS const array ─────────────────────────────────────────
    let mut entries = Vec::new();
    for (key, model_def) in models {
        let variant = match platform_name {
            "metal" => model_def.metal.as_ref(),
            "cuda" => model_def.cuda.as_ref(),
            "cpu" => model_def.cpu.as_ref(),
            _ => None,
        };

        if let Some(pv) = variant {
            entries.push((key.as_str(), model_def, pv));
        }
    }

    writeln!(code, "/// All curated models for the current platform.").unwrap();
    writeln!(code, "pub const MODELS: &[ModelEntry] = &[").unwrap();

    for (key, model_def, pv) in &entries {
        write_model_entry(
            &mut code,
            key,
            model_def.name.as_str(),
            pv,
            &model_def.memory,
        );
    }

    writeln!(code, "];").unwrap();
    writeln!(code).unwrap();

    // ── PlatformDefaults struct ────────────────────────────────────
    writeln!(code, "/// Platform defaults from the registry.").unwrap();
    writeln!(code, "#[derive(Debug, Clone, Copy)]").unwrap();
    writeln!(code, "pub struct PlatformDefaults {{").unwrap();
    writeln!(code, "    /// Default text model registry key.").unwrap();
    writeln!(code, "    pub text: &'static str,").unwrap();
    writeln!(code, "    /// Default vision model registry key.").unwrap();
    writeln!(code, "    pub vision: Option<&'static str>,").unwrap();
    writeln!(code, "}}").unwrap();
    writeln!(code).unwrap();

    // ── DEFAULTS const ─────────────────────────────────────────────
    let vision = match &platform.defaults.vision {
        Some(v) => format!("Some(\"{v}\")"),
        None => "None".to_owned(),
    };

    writeln!(code, "/// Platform defaults for the current build.").unwrap();
    writeln!(
        code,
        "pub const DEFAULTS: PlatformDefaults = PlatformDefaults {{"
    )
    .unwrap();
    writeln!(code, "    text: \"{}\",", platform.defaults.text).unwrap();
    writeln!(code, "    vision: {vision},").unwrap();
    writeln!(code, "}};").unwrap();

    let out_path = out_dir.join("registry.rs");
    std::fs::write(&out_path, code)
        .unwrap_or_else(|e| panic!("failed to write {}: {e}", out_path.display()));
}

// ── Helpers ────────────────────────────────────────────────────────

const MEMORY_THRESHOLDS: &[(&str, &str, u64)] = &[
    ("4gb", "Gb4", 4),
    ("8gb", "Gb8", 8),
    ("16gb", "Gb16", 16),
    ("32gb", "Gb32", 32),
    ("64gb", "Gb64", 64),
];

/// Convert a serde rename key (e.g. "afq4", "q4_0") into an enum variant name.
///
/// Rules: uppercase, replace hyphens/underscores for readability.
fn to_enum_variant(serde_name: &str) -> String {
    serde_name.to_uppercase()
}

/// Convert a loader string from TOML into a `Loader` enum path.
fn loader_variant(loader: &str) -> &'static str {
    match loader {
        "text" => "crate::config::Loader::Text",
        "gguf" => "crate::config::Loader::Gguf",
        "vision" => "crate::config::Loader::Vision",
        "lora" => "crate::config::Loader::Lora",
        "xlora" => "crate::config::Loader::XLora",
        "gguf_lora" => "crate::config::Loader::GgufLora",
        "gguf_xlora" => "crate::config::Loader::GgufXLora",
        other => panic!("unknown loader in registry: {other}"),
    }
}

/// Convert a quantization serde name into a `QuantizationType` enum path.
fn quant_variant(serde_name: &str) -> String {
    let variant = to_enum_variant(serde_name);
    format!("crate::config::QuantizationType::{variant}")
}

/// Convert a memory string (e.g. "8gb") into a `MemoryThreshold` enum path.
fn memory_variant(memory: &str) -> String {
    let variant = MEMORY_THRESHOLDS
        .iter()
        .find(|(name, _, _)| *name == memory)
        .unwrap_or_else(|| panic!("unknown memory threshold: {memory}"))
        .1;
    format!("crate::config::MemoryThreshold::{variant}")
}

fn write_model_entry(
    code: &mut String,
    key: &str,
    name: &str,
    pv: &PlatformVariant,
    memory: &Option<String>,
) {
    let loader = loader_variant(&pv.loader);
    let quant = match &pv.quantization {
        Some(q) => format!("Some({})", quant_variant(q)),
        None => "None".to_owned(),
    };
    let mem = match memory {
        Some(m) => format!("Some({})", memory_variant(m)),
        None => "None".to_owned(),
    };

    writeln!(code, "    ModelEntry {{").unwrap();
    writeln!(code, "        key: \"{key}\",").unwrap();
    writeln!(code, "        name: \"{name}\",").unwrap();
    writeln!(code, "        model_id: \"{}\",", pv.model_id).unwrap();
    writeln!(code, "        loader: {loader},").unwrap();
    writeln!(code, "        quantization: {quant},").unwrap();
    writeln!(code, "        memory: {mem},").unwrap();
    writeln!(code, "    }},").unwrap();
}
